"""Keep rules for what the instrumented tests use from the app.

Reads the test APK's code with dexdump and collects every class, method and field it refers to but doesn't
define itself: those come from the app or the libraries the test APK shares with it. Writes them as keep rules
for the minified build the tests run against, so R8 keeps exactly these and still shrinks, merges and inlines
everything else as in release.

Usage: python3 trace-test-references.py <dexdump> <test apk> <output keep file>
"""
import re
import subprocess
import sys
import tempfile
import zipfile
from collections import defaultdict
from pathlib import Path

PRIMITIVES = {"V": "void", "Z": "boolean", "B": "byte", "S": "short", "C": "char", "I": "int", "J": "long", "F": "float", "D": "double"}
# Provided by the platform, not by the app: nothing to keep.
PLATFORM = ("Ljava/", "Ljavax/", "Landroid/", "Ldalvik/", "Lorg/json/", "Lorg/xml/", "Lorg/w3c/", "Lsun/")


def java_type(descriptor):
    dims = len(descriptor) - len(descriptor.lstrip("["))
    base = descriptor[dims:]
    name = PRIMITIVES.get(base) or base[1:-1].replace("/", ".")
    return name + "[]" * dims


def member_name(name):
    # Kotlin mangles value-class members with a dash (constructor-impl, getZero-F1C5BW0). R8 accepts it, Studio's rules
    # editor doesn't, so the dash is written as `?`: any one character, which matches the same member.
    return name.replace("-", "?")


def parameters(signature):
    return [java_type(t) for t in re.findall(r"\[*(?:L[^;]+;|[VZBSCIJFD])", signature)]


def main(dexdump, apk, out):
    defined, refs, supertypes = set(), defaultdict(set), set()
    with tempfile.TemporaryDirectory() as work, zipfile.ZipFile(apk) as zf:
        for name in (n for n in zf.namelist() if re.fullmatch(r"classes\d*\.dex", n)):
            dex = Path(work) / name
            dex.write_bytes(zf.read(name))
            text = subprocess.run([dexdump, "-d", str(dex)], capture_output=True, text=True, check=True).stdout
            defined |= set(re.findall(r"Class descriptor\s*:\s*'(L[^;]+;)'", text))
            # Supertypes the test classes extend or implement: kept whole, because the test's implementation may be
            # called through any of their methods (kotlinx-coroutines-test's main dispatcher factory was the first).
            for cls in re.findall(r"(?:Superclass|#\d+)\s*:\s*'(L[^;]+;)'", text):
                refs[cls]
                supertypes.add(cls)
            for cls, member, sig in re.findall(r"(L[^;\s]+;)\.([\w$<>-]+):(\S+)\s*//\s*(?:method|field)@", text):
                refs[cls].add((member, sig))
            # Every other type the test code names, in a signature, a field's type or an instruction: it has to exist
            # when the class loads (kotlin.time.TimeSource.WithComparableMarks was the first). The class only, so
            # R8 may still optimise its members.
            for cls in re.findall(r"L[\w/$-]+;", text):
                refs[cls]
    lines = ["# Generated by scripts/trace-test-references.sh: what the instrumented tests use from the app. Don't edit."]
    for cls in sorted(c for c in refs if c not in defined and not c.startswith(PLATFORM)):
        if cls in supertypes:
            lines.append(f"-keep class {java_type(cls)} {{ *; }}")
            continue
        members = []
        for member, sig in sorted(refs[cls]):
            if sig.startswith("("):  # A method.
                args, ret = sig[1:].split(")")
                name = "<init>" if member == "<init>" else member
                members.append(f"    {'' if name == '<init>' else java_type(ret) + ' '}{member_name(name)}({', '.join(parameters(args))});")
            else:
                members.append(f"    {java_type(sig)} {member_name(member)};")
        lines.append(f"-keep class {java_type(cls)}" + (" {\n" + "\n".join(members) + "\n}" if members else ""))
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"{len(lines) - 1} classes kept in {out}")


if __name__ == "__main__":
    main(*sys.argv[1:])
